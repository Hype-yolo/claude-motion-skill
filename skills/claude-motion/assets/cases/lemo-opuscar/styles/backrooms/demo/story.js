const WARP = [[0, 0], [7.0, 7.0], [7.9, 7.6], [39.6, 39.3], [40.2, 39.6], [49.5, 48.9], [54.3, 53.0]];
export function W(t) {
  for (let i = 0; i < WARP.length - 1; i++) { const [a, A] = WARP[i], [b, B] = WARP[i + 1]; if (t <= b) return A + (t - a) * (B - A) / (b - a); }
  const [a, A] = WARP[WARP.length - 1]; return A + (t - a);
}
